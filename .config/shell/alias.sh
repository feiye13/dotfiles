# alias

alias cp="cp --interactive"
alias mv="mv --interactive"
alias rm="rm --interactive=once"

alias ls="ls --color=auto --classify --format=verbose --human-readable --size --sort=extension --time-style=long-iso"
alias la="ls --all --color=auto --classify --format=verbose --human-readable --size --sort=extension --time-style=long-iso"

alias grep="grep --color=auto --line-number --with-filename"
alias df="df --human-readable --print-type"
alias free="free --human --total"
alias dmesg="dmesg --human"
alias du="du --all --human-readable --max-depth=1"
alias uname="uname --all"

alias vi="vim"
